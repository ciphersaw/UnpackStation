    /// <summary>Returns a path to the requested sample, writing it on first use.</summary>
    internal static string Sample(string name)
    {
        if (!Samples.TryGetValue(name, out var encoded))
        {
            throw new ArgumentException($"Unknown test sample: {name}", nameof(name));
        }

        lock (Sync)
        {
            var directory = Path.Combine(AppContext.BaseDirectory, "Data");
            Directory.CreateDirectory(directory);
            var path = Path.Combine(directory, name);
            File.WriteAllBytes(path, Convert.FromBase64String(encoded));
            return path;
        }
    }
